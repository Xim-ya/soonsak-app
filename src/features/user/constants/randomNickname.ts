/**
 * 배열에서 랜덤 요소 선택
 */
function pickRandom<T>(array: readonly T[]): T {
  const index = Math.floor(Math.random() * array.length);
  return array[index] as T;
}

/**
 * 랜덤 닉네임 생성
 *
 * "형용사_배우이름" 형태의 닉네임을 생성합니다.
 * 영화/드라마 앱에 어울리는 재미있는 조합을 만듭니다.
 *
 * @returns 생성된 닉네임 (예: "똑똑한_하정우", "센스있는_손예진")
 *
 * @example
 * const nickname = generateRandomNickname();
 * // "순삭하는_공유", "몰입하는_전도연" 등
 *
 * 총 조합 수: 56 형용사 × 90 배우 = 5,040개
 */
export function generateRandomNickname(): string {
  const adjective = pickRandom(ADJECTIVES);
  const noun = pickRandom(NOUNS);

  return `${adjective}_${noun}`;
}

/**
 * suffix 포함 랜덤 닉네임 생성 (중복 방지용)
 *
 * @param suffixLength suffix 숫자 길이 (기본: 2)
 * @returns 생성된 닉네임 (예: "똑똑한_하정우42")
 */
export function generateRandomNicknameWithSuffix(suffixLength: number = 2): string {
  const base = generateRandomNickname();
  const maxNum = Math.pow(10, suffixLength);
  const suffix = Math.floor(Math.random() * maxNum);

  return `${base}${suffix}`;
}

